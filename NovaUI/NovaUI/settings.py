LOCAL_HTTP_URL_HOSTS = {"localhost", "127.0.0.1", "::1"}


def is_safe_agent_public_url(value):
    parsed = urlparse(str(value or ""))
    if parsed.scheme == "https" and parsed.netloc:
        return True
    if parsed.scheme == "http" and parsed.netloc and parsed.hostname in LOCAL_HTTP_URL_HOSTS:
        return True
    return False


def validate_agent_public_url(name, value, *, required=True):
    if value in (None, ""):
        if required:
            raise ImproperlyConfigured(f"{name} must be set.")
        return value
    if not is_safe_agent_public_url(value):
        raise ImproperlyConfigured(
            f"{name} must use HTTPS, except localhost HTTP is allowed for local development."
        )
    return value


def database_from_url(url):
    parsed = urlparse(url)
    if parsed.scheme in {"postgres", "postgresql"}:
        return {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": unquote(parsed.path.lstrip("/")),
            "USER": unquote(parsed.username or ""),
            "PASSWORD": unquote(parsed.password or ""),
            "HOST": parsed.hostname or "",
            "PORT": str(parsed.port or 5432),
        }
    if parsed.scheme == "sqlite":
        name = unquote(parsed.path)
        if name == "/:memory:":
            name = ":memory:"
        return {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": name,
        }
    raise ImproperlyConfigured(f"Unsupported DATABASE_URL scheme: {parsed.scheme}")


